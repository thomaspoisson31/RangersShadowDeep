import { describe, it, expect, beforeEach } from 'vitest';
import { useGameStore } from '../store/useGameStore';
import { getScenario } from '../utils/gameDataLoader';
import { drawEventCard } from '../utils/rulesEngine';
import { checkLineOfSight } from '../utils/terrainUtils';

describe('Terrain Features & Shadow Deep Cards Engine', () => {
  beforeEach(() => {
    useGameStore.getState().resetGame();
  });

  it('calculates and stores terrain objects when loading a scenario', () => {
    const scenario = getScenario(0, 1); // M01 Scenario 1
    expect(scenario).toBeDefined();

    if (scenario) {
      useGameStore.getState().loadScenario(0, 1, scenario, 'Ranger Valen', []);
      const terrains = useGameStore.getState().terrainObjects;
      expect(terrains.length).toBeGreaterThan(0);

      // Check buildings generated by radial distribution
      const bldg = terrains.find((t) => t.type === 'building');
      expect(bldg).toBeDefined();
      expect(bldg?.x).toBeGreaterThan(0);
      expect(bldg?.y).toBeGreaterThan(0);
    }
  });

  it('toggles door state between open and closed', () => {
    const scenario = getScenario(0, 1);
    if (scenario) {
      useGameStore.getState().loadScenario(0, 1, scenario, 'Ranger Valen', []);
      const terrains = useGameStore.getState().terrainObjects;
      const doorTerrain = terrains.find((t) => t.properties.interactive_door);
      expect(doorTerrain).toBeDefined();

      if (doorTerrain) {
        expect(doorTerrain.properties.interactive_door?.isOpen).toBeFalsy();

        useGameStore.getState().toggleDoorState(doorTerrain.id);
        let updated = useGameStore.getState().terrainObjects.find((t) => t.id === doorTerrain.id);
        expect(updated?.properties.interactive_door?.isOpen).toBe(true);

        useGameStore.getState().toggleDoorState(doorTerrain.id);
        updated = useGameStore.getState().terrainObjects.find((t) => t.id === doorTerrain.id);
        expect(updated?.properties.interactive_door?.isOpen).toBe(false);
      }
    }
  });

  it('toggles burnable state on nest trees', () => {
    const scenario = getScenario(0, 2); // M01 Scenario 2 (Infected Trees)
    if (scenario) {
      useGameStore.getState().loadScenario(0, 2, scenario, 'Ranger Valen', []);
      const terrains = useGameStore.getState().terrainObjects;
      const nestTree = terrains.find((t) => t.properties.burnable);
      expect(nestTree).toBeDefined();

      if (nestTree) {
        expect(nestTree.properties.burned).toBeFalsy();

        useGameStore.getState().toggleBurnableState(nestTree.id);
        let updated = useGameStore.getState().terrainObjects.find((t) => t.id === nestTree.id);
        expect(updated?.properties.burned).toBe(true);
        expect(updated?.properties.blocks_los).toBe(false);
      }
    }
  });

  it('draws cards from Shadow Deep deck fallback when event deck is empty', () => {
    const result = drawEventCard([]);
    expect(result).not.toBeNull();
    expect(result?.card.card).toBeDefined();
    expect(result?.card.description).toBeDefined();
  });

  it('updates line of sight blockage when a door is opened', () => {
    const scenario = getScenario(0, 1);
    if (scenario) {
      useGameStore.getState().loadScenario(0, 1, scenario, 'Ranger Valen', []);
      const terrains = useGameStore.getState().terrainObjects;
      const doorTerrain = terrains.find((t) => t.properties.interactive_door);

      if (doorTerrain) {
        // Line passing through door center
        const p1 = { x: doorTerrain.x - 2, y: doorTerrain.y };
        const p2 = { x: doorTerrain.x + 2, y: doorTerrain.y };

        const initialLoS = checkLineOfSight(p1, p2, useGameStore.getState().terrainObjects);
        expect(initialLoS.hasLoS).toBe(false);

        // Open door
        useGameStore.getState().toggleDoorState(doorTerrain.id);
        const openLoS = checkLineOfSight(p1, p2, useGameStore.getState().terrainObjects);
        expect(openLoS.hasLoS).toBe(true);
      }
    }
  });
});
